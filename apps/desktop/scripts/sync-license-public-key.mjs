import { createPublicKey } from 'node:crypto';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const desktopDir = dirname(scriptsDir);
const workspaceDir = dirname(dirname(desktopDir));

const canonicalSourcePath = join(
  workspaceDir,
  'packages',
  'infrastructure',
  'src',
  'licensing',
  'public-key.ts',
);
const generatedTargetPath = join(desktopDir, 'src', 'license-public-key.generated.ts');

const canonicalSource = await readFile(canonicalSourcePath, 'utf8');
const match = canonicalSource.match(
  /export const EMBEDDED_LICENSE_PUBLIC_KEY_PEM\s*=\s*`([\s\S]*?)`;/,
);
if (!match?.[1]) {
  throw new Error(
    `Could not extract EMBEDDED_LICENSE_PUBLIC_KEY_PEM from ${canonicalSourcePath}`,
  );
}

const pem = match[1].trim();
const parsedKey = createPublicKey(pem);
if (parsedKey.asymmetricKeyType !== 'ed25519') {
  throw new Error(
    `Expected Ed25519 public key in ${canonicalSourcePath}, got ${String(parsedKey.asymmetricKeyType)}`,
  );
}

const expectedContent = [
  '/**',
  ' * AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.',
  ' * Source of truth: `packages/infrastructure/src/licensing/public-key.ts`.',
  ' * Generated by `apps/desktop/scripts/sync-license-public-key.mjs` so Electron',
  ' * main/runtime code inside `app.asar` never imports `@retailos/infrastructure`.',
  ' */',
  `export const EMBEDDED_LICENSE_PUBLIC_KEY_PEM = \`${pem}\`;`,
  '',
].join('\n');

const checkOnly = process.argv.includes('--check');
const currentContent = existsSync(generatedTargetPath)
  ? await readFile(generatedTargetPath, 'utf8')
  : null;

if (checkOnly) {
  if (currentContent !== expectedContent) {
    throw new Error(
      `Out-of-sync embedded public key at ${generatedTargetPath}. Run \`node apps/desktop/scripts/sync-license-public-key.mjs\`.`,
    );
  }
  console.log('Verified desktop embedded license public key matches canonical source.');
} else if (currentContent !== expectedContent) {
  await writeFile(generatedTargetPath, expectedContent, 'utf8');
  console.log(`Synchronized ${generatedTargetPath} from canonical source.`);
} else {
  console.log('Desktop embedded license public key is already up to date.');
}
